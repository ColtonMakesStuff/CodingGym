/*
|--------------------------------------------------------------------------
| Main
|--------------------------------------------------------------------------
*/

async function main() {
  const command = process.argv[2];

  if (command === "help" || command === "--help" || command === "-h") {
    printUsage();
    return;
  }

  if (command === "test" || command === "--test") {
    runCurrentTests();
    return;
  }

  if (command === "solve" || command === "--solve") {
    await solveMode();
    return;
  }

  if (command === "show") {
    showProblem();
    return;
  }

  const hints = hasFlag("--hints");

  if (
    command === undefined ||
    command === "generate" ||
    command === "--generate" ||
    command === "--hints"
  ) {
    let difficulty = null;
    let hints = hasFlag("--hints");

    if (!hasFlag("--no-prompt")) {
      difficulty = await askDifficulty();
      hints = await askHints();
    }

    await generateProblem(hints, difficulty);

    return;
  }

  printUsage();
}

main().catch((error) => {
  console.error("");
  console.error("Coding Gym Error:");
  console.error("");
  console.error(error.message);

  process.exitCode = 1;
});
